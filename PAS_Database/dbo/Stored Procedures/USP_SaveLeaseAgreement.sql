/*************************************************************
 ** File:   [USP_SaveLeaseAgreement]
 ** Description: Saves the Lease Agreement (whole agreement HTML) of ONE lease stockline.
 **              ONE agreement per lease stockline: when a row with the same LeaseHeaderId +
 **              LeaseStocklineId + MasterCompanyId already exists, Save UPDATES it with all the new
 **              values (HTML, dates, terms, ...; the PDF name / path are cleared until the new PDF
 **              is generated); otherwise the first row is inserted (VersionNo = 1). Every change
 **              is kept in LeaseAgreementAudit by the table trigger.
 **              The lease / stockline / part / condition columns are taken from the lease
 **              record itself (not trusted from the screen); the seller / sales person /
 **              dates are defaulted when the caller does not send them:
 **                @AgreementDate    -> today (UTC)
 **                @AgreementDueDate -> LeaseStockline.EndDate
 **                @SalesPersonName  -> LeaseHeader.SalespersonEmployeeId employee name
 **
 **************************************************************
 ** Change History
 **************************************************************
 ** PR   Date           Author                  Change Description
 ** --   --------       -------                 --------------------------------
    1    02/11/2026     Rajesh Gami             [PN-18468] Created - Lease Agreement save
    2    02/11/2026     Rajesh Gami             [PN-18468] Lease terms (editable values of the agreement) saved with the agreement
    3    02/11/2026     Rajesh Gami             [PN-18468] Save updates the existing agreement of the lease stockline (no new version per Save)

exec USP_SaveLeaseAgreement @LeaseHeaderId=1, @LeaseStocklineId=1, @AgreementHtml=N'<div>Agreement</div>', @MasterCompanyId=1, @CreatedBy='Jim Roberts', @UpdatedBy='Jim Roberts'
************************************************************************/
